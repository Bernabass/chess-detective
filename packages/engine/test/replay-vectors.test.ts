import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { ENGINE_VERSION, replay, targetKey } from '../src/index';

interface Vectors {
  engineVersion: string;
  legal: { moves: string[]; finalKey: string }[];
  illegal: { moves: string[]; illegalAt: number; kind: string }[];
}

const vectors = JSON.parse(
  readFileSync(new URL('../../../fixtures/replay-vectors.json', import.meta.url), 'utf8'),
) as Vectors;

// If this fails after a change to the move rules, regenerate the file with
// `pnpm --filter @retrograde/engine fixtures` and commit it (CLAUDE.md, Gotchas).
describe('fixtures/replay-vectors.json is up to date (SPEC §11.2)', () => {
  it('was generated by this engine version, with enough games', () => {
    expect(vectors.engineVersion).toBe(ENGINE_VERSION);
    expect(vectors.legal.length).toBeGreaterThanOrEqual(500);
    expect(vectors.illegal.length).toBeGreaterThanOrEqual(100);
  });

  it('every legal game replays to its finalKey', () => {
    for (const v of vectors.legal) {
      const r = replay(v.moves);
      expect(r.ok && targetKey(r.value)).toBe(v.finalKey);
    }
  }, 30_000);

  it('every illegal game stops at illegalAt', () => {
    for (const v of vectors.illegal) {
      const r = replay(v.moves);
      expect(r.ok ? -1 : r.error.illegalAt, `${v.kind}: ${v.moves[v.illegalAt] ?? ''}`).toBe(
        v.illegalAt,
      );
    }
  }, 30_000);
});
