// `pnpm gen`: regenerates all code derived from api/openapi.yaml and the SQL files.
//   1. Go server interface and models (oapi-codegen)
//   2. Go database code (sqlc)
//   3. TypeScript API types for the web app (openapi-typescript)
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = new URL('..', import.meta.url);
const apiDir = fileURLToPath(new URL('services/api', root));
const specUrl = new URL('api/openapi.yaml', root);
const tsOut = new URL('apps/web/src/api/schema.d.ts', root);

function goTool(name, args) {
  console.log(`> ${name}`);
  const result = spawnSync('go', ['tool', '-modfile=tools/go.mod', name, ...args], {
    cwd: apiDir,
    stdio: 'inherit',
  });
  if (result.error) {
    console.error(
      `gen: could not run go (${result.error.message}). Install Go from https://go.dev/dl/.`,
    );
    process.exit(1);
  }
  if (result.status !== 0) process.exit(result.status ?? 1);
}

goTool('oapi-codegen', ['-config', 'oapi-codegen.yaml', '../../api/openapi.yaml']);
goTool('sqlc', ['generate']);

console.log('> openapi-typescript');
const ast = await openapiTS(readFileSync(specUrl, 'utf8'));
const header = '// Code generated by `pnpm gen` from api/openapi.yaml. DO NOT EDIT.\n\n';
writeFileSync(tsOut, (header + astToString(ast)).replaceAll('\r\n', '\n'));

console.log('gen: done');
